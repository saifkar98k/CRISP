    # -------------------------------------------------------------------------
    # Core Pipeline: Store -> Correlate -> Risk Engine -> Update Risk
    # -------------------------------------------------------------------------

    def _persist_and_correlate(self, event: Dict[str, Any]) -> Dict[str, Any]:
        """
        Executes the live CRISP intelligence pipeline:
        1. Store event in SQLite
        2. Correlate with assets, vulnerabilities, KEV, and NIST CSF 2.0
        3. Invoke explainable multi-factor Risk Engine
        4. Update risk history
        5. Return enriched result with alert status
        """
        now_iso = datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
        with sqlite3.connect(self.db_path) as conn:
            cursor = conn.cursor()
            cursor.execute(
                """
                INSERT OR REPLACE INTO security_events (
                    event_id, timestamp, source_ip, destination_ip,
                    source_port, destination_port, protocol, event_type,
                    severity, status, attack_category, original_attack_label,
                    crisp_attack_category, description, asset_id, nist_function,
                    cve_id, source, dataset_source, crisp_risk_score, imported_at
                ) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?);
                """,
                (
                    event["id"],
                    event["timestamp"],
                    event.get("source_ip"),
                    event.get("destination_ip"),
                    event.get("source_port"),
                    event.get("destination_port"),
                    event.get("protocol", "TCP"),
                    event.get("event_type", "SIMULATION"),
                    event.get("severity", "MEDIUM"),
                    event.get("status", "TRIGGERED"),
                    event.get("attack_category", "Suspicious Activity"),
                    event.get("original_attack_label", event.get("attack_category")),
                    event.get("crisp_attack_category", event.get("attack_category")),
                    event.get("description", "[SIMULATION] Controlled test telemetry"),
                    event.get("asset_id"),
                    event.get("nist_function", "DETECT"),
                    event.get("cve_id"),
                    "SIMULATION",
                    "SIMULATED_DEMO",
                    event.get("crisp_risk_score", 0.0),
                    now_iso,
                ),
            )
            conn.commit()

        # Step 2 & 3: Correlate and Score
        engine = SecurityCorrelationEngine(self.db_path)
        asset_maps = engine._load_assets()
        vuln_map = engine._load_vulnerabilities()

        # Calculate incident frequency for target in last hour
        freq = 1
        with sqlite3.connect(self.db_path) as conn:
            c = conn.cursor()
            target_ip = event.get("destination_ip")
            if target_ip:
                c.execute(
                    "SELECT COUNT(*) FROM security_events WHERE destination_ip = ?",
                    (target_ip,),
                )
                row = c.fetchone()
                if row and row[0]:
                    freq = row[0]

        finding = engine.correlate_event(
            event={
                "event_id": event["id"],
                "timestamp": event["timestamp"],
                "source_ip": event.get("source_ip"),
                "destination_ip": event.get("destination_ip"),
                "attack_category": event.get("attack_category"),
                "severity": event.get("severity"),
                "cve_id": event.get("cve_id"),
            },
            asset_maps=asset_maps,
            vuln_map=vuln_map,
            event_frequency=freq,
        )

        # Step 4: Persist finding and record risk history
        engine.save_findings([finding])

        # Track active alert if finding is CRITICAL
        is_critical = finding.get("risk_level") == "CRITICAL" or finding.get("risk_score", 0) >= 75.0
        if is_critical:
            self._active_alert = {
                "title": "CRITICAL SECURITY EVENT",
                "finding_id": finding["finding_id"],
                "asset": finding.get("asset_name") or finding.get("asset_id") or "Enterprise Asset",
                "risk_score": finding["risk_score"],
                "risk_level": "CRITICAL",
                "attack_category": finding["attack_category"],
                "cve_id": finding.get("cve_id"),
                "known_exploited": finding.get("known_exploited", False),
                "reason": finding.get("explanation") or "Known exploited vulnerability + repeated attack activity",
                "timestamp": event["timestamp"],
                "simulation_label": "SIMULATION MODE",
            }

        with self._lock:
            self._events_generated_count += 1
            self._last_event_time = event["timestamp"]

        return {
            "status": "success",
            "event": event,
            "finding": finding,
            "risk_score": finding.get("risk_score", 0.0),
            "risk_level": finding.get("risk_level", "LOW"),
            "is_critical": is_critical,
            "active_alert": self._active_alert if is_critical else None,
            "simulation_mode": True,
            "disclaimer": "SIMULATION MODE: Synthetic controlled telemetry, not a real attack.",
        }

