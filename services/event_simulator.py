    def generate_event(self, event_type: Optional[str] = None) -> Dict[str, Any]:
        """
        Dispatches and generates a simulation event by type,
        or randomly selects from the 8 simulation types if omitted.
        """
        if not event_type:
            event_type = random.choice(SIMULATION_TYPES)

        etype_lower = event_type.lower()
        if "brute" in etype_lower:
            return self.generate_brute_force()
        elif "port" in etype_lower or "scan" in etype_lower:
            return self.generate_port_scan()
        elif "web" in etype_lower or "sql" in etype_lower:
            return self.generate_web_attack()
        elif "malware" in etype_lower or "bot" in etype_lower:
            return self.generate_malware_event()
        elif "login" in etype_lower or "auth" in etype_lower:
            return self.generate_suspicious_login()
        elif "exfiltration" in etype_lower or "data" in etype_lower:
            return self.generate_data_exfiltration()
        elif "privilege" in etype_lower or "escalat" in etype_lower:
            return self.generate_privilege_escalation()
        elif "vuln" in etype_lower:
            return self.generate_vulnerability_detection()
        elif "crit" in etype_lower:
            return self.generate_critical_event()
        else:
            return self.generate_web_attack()

    # -------------------------------------------------------------------------
    # Background Daemon Simulation Loop
    # -------------------------------------------------------------------------

    def _simulation_worker(self) -> None:
        """Background thread executing controlled simulations at the configured interval."""
        logger.info(f"Simulation worker started (speed: {self._interval_seconds}s).")
        while self._is_running:
            try:
                # Weighted selection: mostly standard attacks, periodic critical/vuln events
                dice = random.random()
                if dice < 0.15:
                    self.generate_critical_event()
                elif dice < 0.35:
                    self.generate_brute_force()
                elif dice < 0.55:
                    self.generate_web_attack()
                elif dice < 0.70:
                    self.generate_port_scan()
                elif dice < 0.85:
                    self.generate_malware_event()
                else:
                    self.generate_suspicious_login()
            except Exception as e:
                logger.error(f"Error in simulation loop: {e}")

            time.sleep(self._interval_seconds)

    def start_simulation(self, interval_seconds: float = 3.0) -> Dict[str, Any]:
        """Starts the background controlled simulation loop."""
        with self._lock:
            self._interval_seconds = max(0.5, float(interval_seconds))
            if not self._is_running:
                self._is_running = True
                self._thread = threading.Thread(target=self._simulation_worker, daemon=True)
                self._thread.start()
                logger.info(f"Controlled simulation started with rate: 1 event per {self._interval_seconds}s.")

        return {
            "status": "running",
            "interval_seconds": self._interval_seconds,
            "events_per_minute": round(60.0 / self._interval_seconds, 1),
            "simulation_mode": True,
            "message": "Controlled security event simulation is now active.",
        }

    def stop_simulation(self) -> Dict[str, Any]:
        """Stops the background simulation loop."""
        with self._lock:
            self._is_running = False
            self._thread = None
            logger.info("Controlled simulation stopped.")

        return {
            "status": "stopped",
            "simulation_mode": True,
            "total_events_generated": self._events_generated_count,
            "message": "Controlled simulation halted.",
        }

    def get_simulation_status(self) -> Dict[str, Any]:
        """Returns the current state and parameters of the simulator."""
        with self._lock:
            return {
                "is_running": self._is_running,
                "interval_seconds": self._interval_seconds,
                "events_per_minute": round(60.0 / self._interval_seconds, 1) if self._is_running else 0.0,
                "events_generated_session": self._events_generated_count,
                "last_event_time": self._last_event_time,
                "simulation_mode": True,
                "active_alert": self._active_alert,
            }

    # -------------------------------------------------------------------------
    # Live Monitoring Metrics & Statistics
    # -------------------------------------------------------------------------

    def get_live_monitoring_stats(self) -> Dict[str, Any]:
        """
        Retrieves real-time monitoring statistics from SQLite:
        - Events per minute (rate over last 60 seconds)
        - Events in last 5 minutes
        - Current composite risk
        - Critical incidents
        - Recent events
        """
        now = datetime.now(timezone.utc)
        now_ts = now.timestamp()
        one_min_ago_iso = datetime.fromtimestamp(now_ts - 60, timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
        five_min_ago_iso = datetime.fromtimestamp(now_ts - 300, timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
        one_hour_ago_iso = datetime.fromtimestamp(now_ts - 3600, timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")

        with sqlite3.connect(self.db_path) as conn:
            conn.row_factory = sqlite3.Row
            cursor = conn.cursor()

            # 1. Events in last 1 minute
            cursor.execute(
                "SELECT COUNT(*) FROM security_events WHERE timestamp >= ?",
                (one_min_ago_iso,),
            )
            events_last_1_min = cursor.fetchone()[0]

            # 2. Events in last 5 minutes
            cursor.execute(
                "SELECT COUNT(*) FROM security_events WHERE timestamp >= ?",
                (five_min_ago_iso,),
            )
            events_last_5_min = cursor.fetchone()[0]

            # Total events
            cursor.execute("SELECT COUNT(*) FROM security_events")
            total_events = cursor.fetchone()[0]

            # 3. Current Risk Score & Level (latest from risk_history or findings)
            cursor.execute("SELECT score, level, explanation FROM risk_history ORDER BY id DESC LIMIT 1")
            last_risk = cursor.fetchone()
            current_risk_score = round(last_risk["score"], 1) if last_risk else 28.0
            current_risk_level = last_risk["level"] if last_risk else "LOW"

            # 4. Critical Incidents (findings with CRITICAL level)
            cursor.execute(
                "SELECT COUNT(*) FROM security_findings WHERE risk_level = 'CRITICAL'"
            )
            critical_incidents_count = cursor.fetchone()[0]

            # Fetch top critical findings
            cursor.execute(
                """
                SELECT finding_id, timestamp, asset_name, cve_id, attack_category,
                       severity, risk_score, risk_level, evidence_json
                FROM security_findings
                WHERE risk_level = 'CRITICAL'
                ORDER BY timestamp DESC LIMIT 5
                """
            )
            critical_findings = []
            for r in cursor.fetchall():
                row_dict = dict(r)
                try:
                    row_dict["evidence"] = json.loads(row_dict.get("evidence_json") or "[]")
                except Exception:
                    row_dict["evidence"] = []
                critical_findings.append(row_dict)

            # 5. Recent events (latest 15)
            cursor.execute(
                """
                SELECT event_id, timestamp, source_ip, destination_ip,
                       attack_category, severity, nist_function, cve_id,
                       dataset_source, description
                FROM security_events
                ORDER BY timestamp DESC, rowid DESC LIMIT 15
                """
            )
            recent_events = [dict(r) for r in cursor.fetchall()]

            # Determine most prominent active critical alert
            active_alert = None
            if critical_findings:
                top_crit = critical_findings[0]
                active_alert = {
                    "title": "CRITICAL SECURITY EVENT",
                    "finding_id": top_crit["finding_id"],
                    "asset": top_crit["asset_name"] or "Production Web Server",
                    "risk_score": top_crit["risk_score"],
                    "risk_level": "CRITICAL",
                    "cve_id": top_crit.get("cve_id"),
                    "attack_category": top_crit.get("attack_category"),
                    "reason": "Known exploited vulnerability + repeated attack activity",
                    "timestamp": top_crit["timestamp"],
                    "simulation_label": "SIMULATION MODE",
                }

        # Calculate rate per minute (fallback to simulated estimate if background simulator is active)
        if self._is_running:
            events_per_minute = max(events_last_1_min, round(60.0 / self._interval_seconds, 1))
        else:
            events_per_minute = events_last_1_min

        return {
            "events_per_minute": events_per_minute,
            "events_last_5_minutes": events_last_5_min,
            "total_events": total_events,
            "current_risk": {
                "score": current_risk_score,
                "level": current_risk_level,
            },
            "critical_incidents": {
                "count": critical_incidents_count,
                "recent_critical": critical_findings,
            },
            "recent_events": recent_events,
            "active_alert": active_alert,
            "simulation_status": {
                "is_running": self._is_running,
                "interval_seconds": self._interval_seconds,
            },
            "simulation_mode": True,
            "disclaimer": "SIMULATION MODE: Synthetic controlled telemetry, not a real attack.",
        }


